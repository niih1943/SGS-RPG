    private void tblOcorrenciasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblOcorrenciasMouseClicked
        int linhaSelecionada = tblOcorrencias.getSelectedRow();

        if (linhaSelecionada >= 0) {

            Ocorrencia ocorrenciaSelecionada
                    = ocorrenciasTabela.get(linhaSelecionada);

            idOcorrenciaSelecionada = ocorrenciaSelecionada.getId();

            txtMissao.setText(
                    String.valueOf(ocorrenciaSelecionada.getMissaoId())
            );

            txtAmeaca.setText(
                    String.valueOf(ocorrenciaSelecionada.getAmeacaId())
            );

            txtDescricao.setText(
                    ocorrenciaSelecionada.getDescricao()
            );

            txtImpNarrativo.setText(
                    ocorrenciaSelecionada.getImpactoNarrativo()
            );

            txtImpSanidade.setText(
                    ocorrenciaSelecionada.getImpactoSanidade()
            );
        }
    }//GEN-LAST:event_tblOcorrenciasMouseClicked

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (idOcorrenciaSelecionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma ocorrência na tabela."
            );
            return;
        }

        Ocorrencia ocorrencia = new Ocorrencia(
                idOcorrenciaSelecionada,
                txtDescricao.getText(),
                txtImpNarrativo.getText(),
                txtImpSanidade.getText(),
                Integer.parseInt(txtMissao.getText()),
                Integer.parseInt(txtAmeaca.getText())
        );

        OcorrenciaDAO dao = new OcorrenciaDAO();
        dao.alterar(ocorrencia);

        JOptionPane.showMessageDialog(
                this,
                "Ocorrência alterada com sucesso!"
        );

        carregarOcorrencias();
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idOcorrenciaSelecionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma ocorrência na tabela."
            );
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Tem certeza que deseja excluir esta ocorrência?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (resposta == JOptionPane.YES_OPTION) {

            if (resposta == JOptionPane.YES_OPTION) {
                OcorrenciaDAO dao = new OcorrenciaDAO();
                boolean excluida = dao.excluir(idOcorrenciaSelecionada);

                if (excluida) {
                    JOptionPane.showMessageDialog(this,
                            "Ocorrência excluída com sucesso!");

                    carregarOcorrencias();

                    idOcorrenciaSelecionada = -1;

                    txtMissao.setText("");
                    txtAmeaca.setText("");
                    txtDescricao.setText("");
                    txtImpNarrativo.setText("");
                    txtImpSanidade.setText("");

                    tblOcorrencias.clearSelection();

                } else {
                    JOptionPane.showMessageDialog(this,
                            "Não foi possível excluir a ocorrência.",
                            "Erro ao excluir",
                            JOptionPane.ERROR_MESSAGE);
                }
            }

        }
    }//GEN-LAST:event_btnExcluirActionPerformed

