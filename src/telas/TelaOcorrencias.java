    private void carregarOcorrencias() {

        OcorrenciaDAO dao = new OcorrenciaDAO();

        ocorrenciasTabela = dao.listar();

        DefaultTableModel modelo
                = (DefaultTableModel) tblOcorrencias.getModel();

        modelo.setRowCount(0);

        for (Ocorrencia ocorrencia : ocorrenciasTabela) {

            modelo.addRow(new Object[]{
                ocorrencia.getMissaoId(),
                ocorrencia.getAmeacaId(),
                ocorrencia.getDescricao(),
                ocorrencia.getImpactoNarrativo(),
                ocorrencia.getImpactoSanidade()
            });
        }
    }

