    private void carregarMissoes() {

        MissaoDAO dao = new MissaoDAO();

        missoesTabela = dao.listar();

        DefaultTableModel modelo = (DefaultTableModel) tblMissoes.getModel();

        modelo.setRowCount(0);

        for (Missao missao : missoesTabela) {

            modelo.addRow(new Object[]{
                missao.getTitulo(),
                missao.getEquipeId(),
                missao.getLocal(),
                missao.getGrauRisco(),
                missao.getStatus(),
                missao.getInicio(),
                missao.getFim()
            });
        }
    }

