    private void carregarAgentes() {

        AgenteDAO dao = new AgenteDAO();

        agentesTabela = dao.listar();

        DefaultTableModel modelo = (DefaultTableModel) tblAgentes.getModel();

        modelo.setRowCount(0);

        for (Agente agente : agentesTabela) {

            modelo.addRow(new Object[]{
                agente.getNome(),
                agente.getCodinome(),
                agente.getClasse(),
                agente.getNivel(),
                agente.getStatus()
            });
        }
    }

