    private void tblAgentesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAgentesMouseClicked
        int linhaSelecionada = tblAgentes.getSelectedRow();

        if (linhaSelecionada >= 0) {

            Agente agenteSelecionado = agentesTabela.get(linhaSelecionada);

            idAgenteSelecionado = agenteSelecionado.getId();

            txtNome.setText(agenteSelecionado.getNome());
            txtCodinome.setText(agenteSelecionado.getCodinome());
            cmbClasse.setSelectedItem(agenteSelecionado.getClasse());
            txtNivel.setText(String.valueOf(agenteSelecionado.getNivel()));
            txtVida.setText(String.valueOf(agenteSelecionado.getVida()));
            txtSanidade.setText(String.valueOf(agenteSelecionado.getSanidade()));
            txtOrigem.setText(agenteSelecionado.getOrigem());
            cmbStatus.setSelectedItem(agenteSelecionado.getStatus());
        }
    }//GEN-LAST:event_tblAgentesMouseClicked

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (idAgenteSelecionado == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um agente na tabela."
            );

            return;
        }

        Agente agente = new Agente(
                idAgenteSelecionado,
                txtNome.getText(),
                txtCodinome.getText(),
                cmbClasse.getSelectedItem().toString(),
                Integer.parseInt(txtNivel.getText()),
                Integer.parseInt(txtVida.getText()),
                Integer.parseInt(txtSanidade.getText()),
                txtOrigem.getText(),
                cmbStatus.getSelectedItem().toString()
        );

        AgenteDAO dao = new AgenteDAO();

        dao.alterar(agente);

        JOptionPane.showMessageDialog(
                this,
                "Agente alterado com sucesso!"
        );

        carregarAgentes();
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idAgenteSelecionado == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um agente na tabela."
            );

            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Tem certeza que deseja excluir este agente?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (resposta == JOptionPane.YES_OPTION) {

            AgenteDAO dao = new AgenteDAO();
            boolean excluido = dao.excluir(idAgenteSelecionado);

            if (excluido) {

                JOptionPane.showMessageDialog(
                        this,
                        "Agente excluído com sucesso!"
                );

                carregarAgentes();

                idAgenteSelecionado = -1;

                txtNome.setText("");
                txtCodinome.setText("");
                txtNivel.setText("");
                txtVida.setText("");
                txtSanidade.setText("");
                txtOrigem.setText("");
                cmbClasse.setSelectedIndex(0);
                cmbStatus.setSelectedIndex(0);

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Não foi possível excluir o agente. "
                        + "Ele pode estar relacionado a outros registros.",
                        "Erro ao excluir",
                        JOptionPane.ERROR_MESSAGE
                );
            }

        }
    }//GEN-LAST:event_btnExcluirActionPerformed

