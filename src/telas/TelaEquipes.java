    private void tblEquipesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblEquipesMouseClicked
        int linhaSelecionada = tblEquipes.getSelectedRow();

        if (linhaSelecionada >= 0) {

            Equipe equipeSelecionada = equipesTabela.get(linhaSelecionada);

            idEquipeSelecionada = equipeSelecionada.getId();

            txtNome.setText(equipeSelecionada.getNome());
            txtDescricao.setText(equipeSelecionada.getDescricao());
        }
    }//GEN-LAST:event_tblEquipesMouseClicked

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (idEquipeSelecionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma equipe na tabela."
            );
            return;
        }

        Equipe equipe = new Equipe(
                idEquipeSelecionada,
                txtNome.getText(),
                txtDescricao.getText()
        );

        EquipeDAO dao = new EquipeDAO();
        dao.alterar(equipe);

        JOptionPane.showMessageDialog(
                this,
                "Equipe alterada com sucesso!"
        );

        carregarEquipes();
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idEquipeSelecionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma equipe na tabela."
            );
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Tem certeza que deseja excluir esta equipe?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (resposta == JOptionPane.YES_OPTION) {

            if (resposta == JOptionPane.YES_OPTION) {

                EquipeDAO dao = new EquipeDAO();
                boolean excluida = dao.excluir(idEquipeSelecionada);

                if (excluida) {

                    JOptionPane.showMessageDialog(
                            this,
                            "Equipe excluída com sucesso!"
                    );

                    carregarEquipes();

                    idEquipeSelecionada = -1;

                    txtNome.setText("");
                    txtDescricao.setText("");
                    tblEquipes.clearSelection();

                } else {

                    JOptionPane.showMessageDialog(
                            this,
                            "Não foi possível excluir a equipe. "
                            + "Ela pode estar vinculada a uma missão.",
                            "Erro ao excluir",
                            JOptionPane.ERROR_MESSAGE
                    );
                }
            }

        }
    }//GEN-LAST:event_btnExcluirActionPerformed

