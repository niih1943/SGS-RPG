    private void carregarEquipes() {
        EquipeDAO dao = new EquipeDAO();

        equipesTabela = dao.listar();

        DefaultTableModel modelo = (DefaultTableModel) tblEquipes.getModel();

        modelo.setRowCount(0);

        for (Equipe equipe : equipesTabela) {
            modelo.addRow(new Object[]{
                equipe.getNome(),
                equipe.getDescricao()
            });
        }
    }

