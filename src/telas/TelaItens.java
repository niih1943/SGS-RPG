    private void tblItensMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblItensMouseClicked
        int linhaSelecionada = tblItens.getSelectedRow();

        if (linhaSelecionada >= 0) {

            Item itemSelecionado = itensTabela.get(linhaSelecionada);

            idItemSelecionado = itemSelecionado.getId();

            txtNome.setText(itemSelecionado.getNome());
            txtCategoria.setText(itemSelecionado.getCategoria());
            txtEfeito.setText(itemSelecionado.getEfeito());
            txtPerigo.setText(String.valueOf(itemSelecionado.getNivelPerigo()));
            txtAgente.setText(String.valueOf(itemSelecionado.getAgenteId()));
            cmbStatus.setSelectedItem(itemSelecionado.getStatus());
        }
    }//GEN-LAST:event_tblItensMouseClicked

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (idItemSelecionado == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um item na tabela."
            );
            return;
        }

        Item item = new Item(
                idItemSelecionado,
                txtNome.getText(),
                txtCategoria.getText(),
                txtEfeito.getText(),
                Integer.parseInt(txtPerigo.getText()),
                cmbStatus.getSelectedItem().toString(),
                Integer.parseInt(txtAgente.getText())
        );

        ItemDAO dao = new ItemDAO();
        dao.alterar(item);

        JOptionPane.showMessageDialog(
                this,
                "Item alterado com sucesso!"
        );

        carregarItens();
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idItemSelecionado == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um item na tabela."
            );
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Tem certeza que deseja excluir este item?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (resposta == JOptionPane.YES_OPTION) {

            if (resposta == JOptionPane.YES_OPTION) {

                ItemDAO dao = new ItemDAO();
                boolean excluido = dao.excluir(idItemSelecionado);

                if (excluido) {

                    JOptionPane.showMessageDialog(
                            this,
                            "Item excluído com sucesso!"
                    );

                    carregarItens();

                    idItemSelecionado = -1;

                    txtNome.setText("");
                    txtCategoria.setText("");
                    txtEfeito.setText("");
                    txtPerigo.setText("");
                    txtAgente.setText("");
                    cmbStatus.setSelectedIndex(0);
                    tblItens.clearSelection();

                } else {

                    JOptionPane.showMessageDialog(
                            this,
                            "Não foi possível excluir o item.",
                            "Erro ao excluir",
                            JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

