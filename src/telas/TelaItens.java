    private void carregarItens() {

        ItemDAO dao = new ItemDAO();

        itensTabela = dao.listar();

        DefaultTableModel modelo
                = (DefaultTableModel) tblItens.getModel();

        modelo.setRowCount(0);

        for (Item item : itensTabela) {

            modelo.addRow(new Object[]{
                item.getNome(),
                item.getCategoria(),
                item.getEfeito(),
                item.getNivelPerigo(),
                item.getAgenteId(),
                item.getStatus()
            });
        }
    }

