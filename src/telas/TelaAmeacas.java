    private void tblAmeacasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAmeacasMouseClicked
        int linhaSelecionada = tblAmeacas.getSelectedRow();

        if (linhaSelecionada >= 0) {

            Ameaca ameacaSelecionada = ameacasTabela.get(linhaSelecionada);

            idAmeacaSelecionada = ameacaSelecionada.getId();

            txtNome.setText(ameacaSelecionada.getNome());
            cmbTipo.setSelectedItem(ameacaSelecionada.getTipo());
            cmbElemento.setSelectedItem(ameacaSelecionada.getElemento());
            txtNivel.setText(String.valueOf(ameacaSelecionada.getNivelAmeaca()));
            cmbAparicao.setSelectedItem(ameacaSelecionada.getStatusAparicao());
        }
    }//GEN-LAST:event_tblAmeacasMouseClicked

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (idAmeacaSelecionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma ameaça na tabela."
            );
            return;
        }

        Ameaca ameaca = new Ameaca(
                idAmeacaSelecionada,
                txtNome.getText(),
                cmbTipo.getSelectedItem().toString(),
                cmbElemento.getSelectedItem().toString(),
                Integer.parseInt(txtNivel.getText()),
                cmbAparicao.getSelectedItem().toString()
        );

        AmeacaDAO dao = new AmeacaDAO();
        dao.alterar(ameaca);

        JOptionPane.showMessageDialog(
                this,
                "Ameaça alterada com sucesso!"
        );

        carregarAmeacas();
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idAmeacaSelecionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma ameaça na tabela."
            );
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Tem certeza que deseja excluir esta ameaça?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (resposta == JOptionPane.YES_OPTION) {

            if (resposta == JOptionPane.YES_OPTION) {

                AmeacaDAO dao = new AmeacaDAO();
                boolean excluida = dao.excluir(idAmeacaSelecionada);

                if (excluida) {

                    JOptionPane.showMessageDialog(
                            this,
                            "Ameaça excluída com sucesso!"
                    );

                    carregarAmeacas();

                    idAmeacaSelecionada = -1;

                    txtNome.setText("");
                    txtNivel.setText("");
                    cmbTipo.setSelectedIndex(0);
                    cmbElemento.setSelectedIndex(0);
                    cmbAparicao.setSelectedIndex(0);
                    tblAmeacas.clearSelection();

                } else {

                    JOptionPane.showMessageDialog(
                            this,
                            "Não foi possível excluir a ameaça. "
                            + "Ela pode estar vinculada a uma ocorrência.",
                            "Erro ao excluir",
                            JOptionPane.ERROR_MESSAGE
                    );
                }
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

