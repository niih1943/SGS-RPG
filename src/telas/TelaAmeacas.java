    private void carregarAmeacas() {

        AmeacaDAO dao = new AmeacaDAO();

        ameacasTabela = dao.listar();

        DefaultTableModel modelo = (DefaultTableModel) tblAmeacas.getModel();

        modelo.setRowCount(0);

        for (Ameaca ameaca : ameacasTabela) {

            modelo.addRow(new Object[]{
                ameaca.getNome(),
                ameaca.getTipo(),
                ameaca.getElemento(),
                ameaca.getNivelAmeaca(),
                ameaca.getStatusAparicao()
            });
        }
    }

